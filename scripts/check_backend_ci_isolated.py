"""Execute cloud-CI-equivalent integration in isolated schema/Redis DB/index."""
import os,sys,time,uuid,subprocess,json
from pathlib import Path
from urllib.request import urlopen
from sqlalchemy import text
from app.database import engine
from app.config import settings
from elasticsearch import Elasticsearch
name='cineagent_ci_'+uuid.uuid4().hex[:12]
with engine.begin() as c:c.execute(text('CREATE SCHEMA '+name))
env=dict(os.environ,PGOPTIONS='-c search_path='+name,CINEAGENT_CI='1',MOVIE_INDEX_NAME=name,JOB_BROKER_DB='3',JOB_QUEUE=name,REDIS_URL=settings.redis_url.rsplit('/',1)[0]+'/3',BACKEND_TEST_URL='http://127.0.0.1:18001',PYTHONPATH='/app')
children=[];logs=[]
def run(args):subprocess.run([sys.executable,*args],env=env,check=True,cwd='/app')
try:
    run(['/checks/prepare_backend_ci.py']);run(['-m','alembic','upgrade','head']);run(['-m','alembic','upgrade','head'])
    for label,args in [('api',['-m','uvicorn','app.ci_app:app','--host','127.0.0.1','--port','18001']),('worker',['-m','celery','-A','app.jobs.tasks:celery_app','worker','--pool=solo','--loglevel=WARNING','-Q',name]),('dispatcher',['-m','app.jobs.dispatcher'])]:
        log=open('/trial-ledger/BACKEND_CI_'+label+'.log','w');logs.append(log);children.append(subprocess.Popen([sys.executable,*args],env=env,cwd='/app',stdout=log,stderr=subprocess.STDOUT))
    for _ in range(40):
        try:
            with urlopen('http://127.0.0.1:18001/openapi.json',timeout=1):break
        except Exception:time.sleep(.5)
    run(['-m','pytest','-q','-p','no:cacheprovider','/app/tests','--junitxml=/trial-ledger/BACKEND_CI_LOCAL.xml'])
    Path('/trial-ledger/BACKEND_CI_LOCAL.json').write_text(json.dumps({'isolated_schema':True,'separate_redis_db':3,'separate_es_index':True,'double_migration':True,'suite_passed':True,'github_cloud_run':False},indent=2))
finally:
    for child in children:child.terminate()
    for child in children:
        try:child.wait(timeout=10)
        except subprocess.TimeoutExpired:child.kill();child.wait()
    for log in logs:log.close()
    with engine.begin() as c:c.execute(text('DROP SCHEMA '+name+' CASCADE'))
    with Elasticsearch(settings.elasticsearch_url) as es:
        if es.indices.exists(index=name):es.indices.delete(index=name)
    import redis
    r=redis.Redis.from_url(env['REDIS_URL'])
    # Dedicated CI-only Redis DB; remove only names generated by this test/queue.
    for k in r.scan_iter(match='*'+name+'*'):r.delete(k)
